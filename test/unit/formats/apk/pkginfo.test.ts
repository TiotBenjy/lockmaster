import { describe, expect, it } from 'vitest';
import { parseApkDependencies, parsePkgInfo } from '../../../../src/formats/apk/pkginfo.js';
import { DEFAULT_LIMITS } from '../../../../src/formats/common/limits.js';

const parse = (text: string) => parsePkgInfo(Buffer.from(text, 'utf8'), DEFAULT_LIMITS);

function codeOf(text: string | Uint8Array): string {
  try {
    parsePkgInfo(typeof text === 'string' ? Buffer.from(text, 'utf8') : text, DEFAULT_LIMITS);
    return 'aucune erreur';
  } catch (error) {
    return (error as { code?: string }).code ?? `erreur sans code : ${String(error)}`;
  }
}

describe('parsePkgInfo', () => {
  it('lit les clés simples et répétées, ignore commentaires et lignes vides', () => {
    const info = parse('# Generated by abuild\n\npkgname = hello\ndepend = a\ndepend = b c\npkgdesc = un = deux\n');
    expect(info.get('pkgname')).toBe('hello');
    expect(info.get('pkgdesc')).toBe('un = deux');
    expect(info.all('depend')).toEqual(['a', 'b c']);
    expect(info.get('absent')).toBeUndefined();
    expect(info.entries).toEqual([
      ['pkgname', 'hello'],
      ['depend', 'a'],
      ['depend', 'b c'],
      ['pkgdesc', 'un = deux'],
    ]);
  });

  it.each([
    ['clé simple répétée', 'pkgname = a\npkgname = b\n'],
    ['ligne sans « = »', 'pkgname=hello\n'],
    ['clé invalide', 'Pkg Name = a\n'],
    ['retour chariot', 'pkgname = a\r\n'],
    ['tabulation', 'pkgdesc = a\tb\n'],
    ['caractère C1', 'pkgdesc = a\u0085\n'],
    ['U+FFFF', 'pkgdesc = a\uffff\n'],
  ])('refuse : %s (FORMAT_INVALID)', (_label, text) => {
    expect(codeOf(text)).toBe('FORMAT_INVALID');
  });

  it('refuse un UTF-8 invalide et un texte trop long', () => {
    expect(codeOf(Uint8Array.of(0x70, 0x20, 0x3d, 0x20, 0xff, 0x0a))).toBe('FORMAT_INVALID');
    expect(codeOf(`pkgdesc = ${'x'.repeat(DEFAULT_LIMITS.maxControlTextBytes)}\n`)).toBe('FORMAT_LIMIT_EXCEEDED');
  });
});

describe('parseApkDependencies', () => {
  it('lit noms, opérateurs, conflits, étiquettes et listes séparées par des espaces', () => {
    expect(
      parseApkDependencies(['so:libc.musl-x86_64.so.1 busybox>=1.36', '!old<2.0 cmd:[ pkg@edge~1.2 a=1 b<1 c>2 d<=3']),
    ).toEqual({
      depends: [
        { name: 'so:libc.musl-x86_64.so.1' },
        { name: 'busybox', operator: 'ge', version: '1.36' },
        { name: 'cmd:[' },
        { name: 'pkg', operator: 'fuzzy', version: '1.2', qualifier: 'edge' },
        { name: 'a', operator: 'eq', version: '1' },
        { name: 'b', operator: 'lt', version: '1' },
        { name: 'c', operator: 'gt', version: '2' },
        { name: 'd', operator: 'le', version: '3' },
      ],
      conflicts: [{ name: 'old', operator: 'lt', version: '2.0' }],
    });
  });

  it.each(['a>=', 'a=1.0bc', '<1', 'a><Q1abc', 'a=>1', '!', 'a@', 'a\u0001'])(
    'refuse « %s » (FORMAT_INVALID)',
    (token) => {
      expect(() => parseApkDependencies([token])).toThrowError(expect.objectContaining({ code: 'FORMAT_INVALID' }));
    },
  );
});
